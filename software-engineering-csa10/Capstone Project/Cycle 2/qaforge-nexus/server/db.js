'use strict';
/**
 * QAForge Nexus - database layer for PostgreSQL 14+ (via the bundled zero-dependency client in ./pgclient.js).
 *
 *   DATABASE_URL = postgres://user:password@host:5432/dbname[?sslmode=require]
 *   PGPOOL_MAX   = maximum pooled connections (default 10)
 *
 * The helpers keep the shape used throughout the code base but are asynchronous:
 *   all(sql, ...params)  -> rows[]         get(sql, ...params) -> row | undefined
 *   run(sql, ...params)  -> { lastInsertRowid, changes }       tx(async () => { ... }) -> result
 * SQL is written with "?" placeholders and translated to $1..$n; LIKE is case-insensitive (ILIKE); INSERTs into tables that have
 * an "id" identity column automatically RETURN it. Transactions are bound to the async call chain, so nested helpers
 * automatically use the transaction's connection.
 */
const { AsyncLocalStorage } = require('node:async_hooks');
const { Pool } = require('./pgclient');

const DATABASE_URL = process.env.DATABASE_URL || 'postgres://qaforge:qaforge@127.0.0.1:5432/qaforge';
const pool = new Pool(DATABASE_URL, { max: Number(process.env.PGPOOL_MAX) || 10 });
const als = new AsyncLocalStorage();

const NO_ID_TABLES = new Set(['project_members', 'counters']);

function translate(sql, params) {
  let out = ''; let n = 0; let inStr = false;
  for (const ch of sql) {
    if (ch === "'") inStr = !inStr;
    if (ch === '?' && !inStr) out += `$${++n}`; else out += ch;
  }
  let text = out;
  const orIgnore = /^\s*INSERT\s+OR\s+IGNORE\s+INTO/i.test(text);
  if (orIgnore) text = text.replace(/INSERT\s+OR\s+IGNORE\s+INTO/i, 'INSERT INTO') + ' ON CONFLICT DO NOTHING';
  text = text.replace(/\bLIKE\b/g, 'ILIKE');
  let returnsId = false;
  const m = /^\s*INSERT\s+INTO\s+([a-z_]+)/i.exec(text);
  if (m && !/\bRETURNING\b/i.test(text) && !NO_ID_TABLES.has(m[1].toLowerCase())) { text += ' RETURNING id'; returnsId = true; }
  if (n !== params.length) throw new Error(`SQL has ${n} placeholders but ${params.length} parameters were given: ${sql.slice(0, 80)}`);
  return { text, returnsId };
}

const clean = (p) => p.map((v) => (v === undefined ? null : typeof v === 'boolean' ? (v ? 1 : 0) : v));

function exec(client, sql, params) {
  const { text, returnsId } = translate(sql, params);
  return (client || pool).query(text, clean(params)).then((r) => ({ ...r, returnsId }));
}
const current = () => als.getStore();

async function all(sql, ...p) { return (await exec(current(), sql, p)).rows; }
async function get(sql, ...p) { return (await exec(current(), sql, p)).rows[0]; }
async function run(sql, ...p) {
  const r = await exec(current(), sql, p);
  return { lastInsertRowid: r.returnsId && r.rows[0] ? r.rows[0].id : undefined, changes: r.rowCount, rows: r.rows };
}

async function tx(fn) {
  if (current()) return fn(); // re-entrant: join the outer transaction
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const r = await als.run(client, fn);
    await client.query('COMMIT');
    return r;
  } catch (e) {
    try { await client.query('ROLLBACK'); } catch (_) { /* connection already gone */ }
    throw e;
  } finally { client.release(); }
}

const now = () => new Date().toISOString();

async function nextCode(projectId, kind, prefix, pad = 4) {
  const row = await get(
    `INSERT INTO counters(project_id, kind, value) VALUES(?, ?, 1)
     ON CONFLICT(project_id, kind) DO UPDATE SET value = counters.value + 1 RETURNING value`,
    projectId, kind
  );
  return `${prefix}-${String(row.value).padStart(pad, '0')}`;
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS departments(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS users(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, emp_code TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  email TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin','qa_manager','qa_engineer','developer','product_owner','viewer')),
  department_id INTEGER REFERENCES departments(id), designation TEXT,
  active INTEGER NOT NULL DEFAULT 1, must_change_password INTEGER NOT NULL DEFAULT 0,
  failed_logins INTEGER NOT NULL DEFAULT 0, locked_until TIMESTAMPTZ, last_login TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS projects(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, key TEXT UNIQUE NOT NULL, name TEXT NOT NULL, description TEXT,
  base_url TEXT, owner_id INTEGER REFERENCES users(id), status TEXT NOT NULL DEFAULT 'active',
  source_dataset TEXT, source_url TEXT,
  created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS project_members(
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id),
  PRIMARY KEY(project_id, user_id)
);
CREATE TABLE IF NOT EXISTS counters(
  project_id INTEGER NOT NULL, kind TEXT NOT NULL, value INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(project_id, kind)
);
CREATE TABLE IF NOT EXISTS requirements(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  code TEXT NOT NULL, title TEXT NOT NULL, description TEXT,
  priority TEXT NOT NULL DEFAULT 'P2', status TEXT NOT NULL DEFAULT 'approved',
  created_by INTEGER, created_at TIMESTAMPTZ NOT NULL, UNIQUE(project_id, code)
);
CREATE TABLE IF NOT EXISTS suites(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL, description TEXT, sort_order INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS test_cases(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  suite_id INTEGER REFERENCES suites(id), requirement_id INTEGER REFERENCES requirements(id),
  code TEXT NOT NULL, title TEXT NOT NULL, description TEXT,
  type TEXT NOT NULL DEFAULT 'functional', priority TEXT NOT NULL DEFAULT 'P2',
  preconditions TEXT, steps_text TEXT, expected_text TEXT,
  method TEXT, endpoint TEXT, headers JSONB, body TEXT, assertions JSONB, extract JSONB,
  timeout_ms INTEGER NOT NULL DEFAULT 10000,
  automated INTEGER NOT NULL DEFAULT 0, is_setup INTEGER NOT NULL DEFAULT 0,
  depends_on_previous INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'ready', sort_order INTEGER NOT NULL DEFAULT 0,
  external_ref TEXT,
  created_by INTEGER, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
  UNIQUE(project_id, code)
);
CREATE TABLE IF NOT EXISTS test_runs(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  code TEXT NOT NULL, name TEXT NOT NULL, environment TEXT, trigger_type TEXT NOT NULL DEFAULT 'automated',
  status TEXT NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','completed','aborted')), started_by INTEGER, started_at TIMESTAMPTZ NOT NULL, finished_at TIMESTAMPTZ,
  total INTEGER NOT NULL DEFAULT 0, passed INTEGER NOT NULL DEFAULT 0, failed INTEGER NOT NULL DEFAULT 0,
  errored INTEGER NOT NULL DEFAULT 0, blocked INTEGER NOT NULL DEFAULT 0, skipped INTEGER NOT NULL DEFAULT 0,
  flaky INTEGER NOT NULL DEFAULT 0, duration_ms INTEGER NOT NULL DEFAULT 0, retries INTEGER NOT NULL DEFAULT 0,
  notes TEXT, UNIQUE(project_id, code)
);
CREATE TABLE IF NOT EXISTS test_results(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id INTEGER NOT NULL REFERENCES test_runs(id) ON DELETE CASCADE,
  test_case_id INTEGER NOT NULL REFERENCES test_cases(id),
  status TEXT NOT NULL CHECK(status IN ('passed','failed','error','blocked','skipped')),
  prereq INTEGER NOT NULL DEFAULT 0, attempts INTEGER NOT NULL DEFAULT 1, flaky INTEGER NOT NULL DEFAULT 0,
  duration_ms INTEGER NOT NULL DEFAULT 0, request_snapshot TEXT, response_status INTEGER,
  response_excerpt TEXT, failure_reason TEXT, assertion_log TEXT, defect_id INTEGER,
  executed_by INTEGER, executed_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS defects(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  code TEXT NOT NULL, title TEXT NOT NULL, description TEXT,
  severity TEXT NOT NULL DEFAULT 'Medium' CHECK(severity IN ('Critical','High','Medium','Low')),
  priority TEXT NOT NULL DEFAULT 'P3' CHECK(priority IN ('P1','P2','P3','P4')),
  status TEXT NOT NULL DEFAULT 'New' CHECK(status IN ('New','Assigned','In Progress','Fixed','Retesting','Verified','Closed','Reopened','Rejected','Deferred','Duplicate')),
  type TEXT NOT NULL DEFAULT 'functional',
  source TEXT NOT NULL DEFAULT 'manual', test_case_id INTEGER REFERENCES test_cases(id),
  run_id INTEGER REFERENCES test_runs(id), requirement_id INTEGER REFERENCES requirements(id),
  reporter_id INTEGER REFERENCES users(id), assignee_id INTEGER REFERENCES users(id),
  steps TEXT, expected TEXT, actual TEXT, evidence TEXT, environment TEXT,
  occurrences INTEGER NOT NULL DEFAULT 1, reopen_count INTEGER NOT NULL DEFAULT 0,
  duplicate_of INTEGER REFERENCES defects(id), resolution TEXT,
  external_ref TEXT, external_url TEXT,
  created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, resolved_at TIMESTAMPTZ, closed_at TIMESTAMPTZ, sla_due TIMESTAMPTZ,
  UNIQUE(project_id, code)
);
CREATE TABLE IF NOT EXISTS defect_history(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, defect_id INTEGER NOT NULL REFERENCES defects(id) ON DELETE CASCADE,
  actor_id INTEGER, action TEXT NOT NULL, from_status TEXT, to_status TEXT, note TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS defect_comments(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, defect_id INTEGER NOT NULL REFERENCES defects(id) ON DELETE CASCADE,
  author_id INTEGER NOT NULL, body TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS audit_log(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id INTEGER, action TEXT NOT NULL, entity TEXT, entity_id TEXT,
  detail TEXT, ip TEXT, created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS notifications(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL, message TEXT NOT NULL, link TEXT,
  is_read INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_tc_project ON test_cases(project_id, suite_id, sort_order);
CREATE INDEX IF NOT EXISTS ix_res_run ON test_results(run_id);
CREATE INDEX IF NOT EXISTS ix_res_tc ON test_results(test_case_id, executed_at);
CREATE INDEX IF NOT EXISTS ix_def_project ON defects(project_id, status);
CREATE INDEX IF NOT EXISTS ix_def_tc ON defects(test_case_id);
CREATE INDEX IF NOT EXISTS ix_def_assignee ON defects(assignee_id, status);
CREATE INDEX IF NOT EXISTS ix_hist_def ON defect_history(defect_id);
CREATE INDEX IF NOT EXISTS ix_runs_project ON test_runs(project_id, started_at);
CREATE INDEX IF NOT EXISTS ix_notif_user ON notifications(user_id, is_read);
CREATE INDEX IF NOT EXISTS ix_audit_time ON audit_log(created_at DESC);
`;

async function initSchema() { await pool.exec(SCHEMA); }
async function resetSchema() { await pool.exec('DROP SCHEMA IF EXISTS public CASCADE; CREATE SCHEMA public;'); }
async function close() { await pool.end(); }

module.exports = { pool, all, get, run, tx, now, nextCode, initSchema, resetSchema, close, DATABASE_URL, SCHEMA };
